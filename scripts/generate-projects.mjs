// One-off generator: turns the REA-captured project tables into typed source.
// Source: data/source/pnc-projects-raw.json (captured from pncinfratech.com project pages).
// Usage: node scripts/generate-projects.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = JSON.parse(readFileSync(join(root, "data/source/pnc-projects-raw.json"), "utf8"));

// Canonical state names; spelling variants on the source site are normalised here.
const STATE_ALIASES = {
  "Gujarat": ["Gujarat"],
  "Madhya Pradesh": ["Madhya Pradesh"],
  "Maharashtra": ["Maharashtra"],
  "Rajasthan": ["Rajasthan"],
  "Bihar": ["Bihar"],
  "Uttar Pradesh": ["Uttar Pradesh"],
  "Uttar Pardesh": ["Uttar Pradesh"],
  "Haryana": ["Haryana"],
  "Uttarakhand": ["Uttarakhand"],
  "Karnataka": ["Karnataka"],
  "MP/UP": ["Madhya Pradesh", "Uttar Pradesh"],
  "Andhra Pradesh": ["Andhra Pradesh"],
  "New Delhi": ["Delhi"],
  "Chhattisgarh": ["Chhattisgarh"],
  "Punjab": ["Punjab"],
  "Rajasthan/ Madhya Pradesh": ["Rajasthan", "Madhya Pradesh"],
  "Uttar Pradesh & Uttrakhand": ["Uttar Pradesh", "Uttarakhand"],
  "Uttar Pradesh & Madhaya Pradesh": ["Uttar Pradesh", "Madhya Pradesh"],
  "West Bengal": ["West Bengal"],
  "Tamil Nadu": ["Tamil Nadu"],
  "Assam": ["Assam"],
};

// Section code -> sector / delivery / status.
const SECTIONS = {
  "1.1": { sector: "highway", delivery: "EPC", status: "ongoing" },
  "1.2": { sector: "rail", delivery: "EPC", status: "ongoing" },
  "1.3": { sector: "airport", delivery: "EPC", status: "ongoing" },
  "2.1": { sector: "highway", delivery: "BOT/HAM", status: "ongoing" },
  "2.2": { sector: "highway", delivery: "BOT/HAM", status: "operating" },
  "3.1": { sector: "water", delivery: null, status: "ongoing" },
  "3.2": { sector: "water", delivery: null, status: "ongoing" },
  "4": { sector: "industrial", delivery: null, status: "operating" },
  "5": { sector: "coal", delivery: null, status: null },
  "6.1": { sector: "highway", delivery: null, status: "completed" },
  "6.2": { sector: "airport", delivery: null, status: "completed" },
  "6.3": { sector: "bridge", delivery: null, status: "completed" },
  "6.4": { sector: "power", delivery: null, status: "completed" },
  "6.5": { sector: "water", delivery: null, status: "completed" },
};

const clean = (s) => s.replace(/\s+/g, " ").trim();
const projects = [];

for (const [page, rows] of Object.entries(raw)) {
  const counters = {};
  for (const { section, cells } of rows) {
    const code = section.match(/^(\d+(?:\.\d+)?)\.?\s/)?.[1];
    const meta = code && SECTIONS[code];
    if (!meta) throw new Error(`Unmapped section "${section}" on ${page}`);
    const [, name, employer, location] = cells;
    const states = STATE_ALIASES[location.trim()];
    if (!states) throw new Error(`Unmapped location "${location}" (${page}, ${code})`);
    counters[code] = (counters[code] ?? 0) + 1;
    projects.push({
      id: `${code.replace(".", "-")}-${String(counters[code]).padStart(2, "0")}`,
      name: clean(name),
      employer: clean(employer),
      locationLabel: clean(location),
      states,
      ...meta,
      source: `${page}.html`,
    });
  }
}

const header = `// GENERATED by scripts/generate-projects.mjs from data/source/pnc-projects-raw.json.
// Do not edit by hand. Names/employers are verbatim from pncinfratech.com project pages;
// only state names are normalised (e.g. "Uttar Pardesh" -> "Uttar Pradesh").
import type { Project } from "./project-types";

export const projects: Project[] = `;

writeFileSync(join(root, "src/data/projects.ts"), header + JSON.stringify(projects, null, 2) + ";\n");
console.log(`Wrote ${projects.length} projects`);
